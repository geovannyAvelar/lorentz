# Lorentz Engine
# Embeds a directory tree (the web UI's static export, web/out) into a single
# generated C source file: one byte array per file plus a webui_files[]
# lookup table (struct webui_file, declared in webui.h) that webui_handler()
# serves from memory. Invoked by CMakeLists.txt at build time, after `npm run
# build:embed` has produced $1.
